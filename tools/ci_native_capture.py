"""Capture the running native FontStrike window; never draw, composite or substitute UI pixels."""
from __future__ import annotations

import datetime
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

from PIL import Image, UnidentifiedImageError


def inspect_pixels(image: Image.Image) -> dict:
    width, height = image.size
    if width < 900 or height < 600 or width > 4096 or height > 4096:
        raise ValueError('Native frame is outside the documented minimum/bounded size')
    rgb = image.convert('RGB')
    pixels = [rgb.getpixel((x, y))
              for y in range(0, height, max(1, height // 64))
              for x in range(0, width, max(1, width // 64))]
    values = [sum(pixel) // 3 for pixel in pixels]
    colors = len(set(pixels))
    span = max(values) - min(values)
    if colors < 32 or span < 40:
        raise ValueError('Native frame lacks rendered detail')
    return {'width': width, 'height': height,
            'sampled_colors': colors, 'sampled_value_range': span}


def validate_native_png(path: Path) -> dict:
    raw = path.read_bytes()
    if not 10000 <= len(raw) <= 5 * 1024 * 1024:
        raise ValueError('Native PNG byte size is outside the bounded range')
    try:
        with Image.open(path) as image:
            if image.format != 'PNG':
                raise ValueError('Native capture is not a PNG')
            result = inspect_pixels(image)
    except (UnidentifiedImageError, OSError) as error:
        raise ValueError(f'Native PNG cannot be decoded: {error}') from error
    return {'file': path.name, 'bytes': len(raw),
            'sha256': hashlib.sha256(raw).hexdigest(), **result}


def capture(app: Path, output: Path) -> None:
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip()
    if head != os.environ.get('FONTSTRIKE_EXPECTED_HEAD'):
        raise RuntimeError('Capture checkout differs from requested source head')
    if not os.environ.get('DISPLAY'):
        raise RuntimeError('A real X11 display must host the native window')
    if os.environ.get('LIBGL_ALWAYS_SOFTWARE') != '1' or os.environ.get('GALLIUM_DRIVER') != 'llvmpipe':
        raise RuntimeError('Expected the explicitly selected Mesa software OpenGL driver')
    output.mkdir(parents=True, exist_ok=True)
    glx = (output / 'glxinfo.txt').read_text()
    renderer_lines = [line.strip() for line in glx.splitlines()
                      if 'OpenGL renderer string:' in line]
    if not renderer_lines or 'llvmpipe' not in renderer_lines[0].lower():
        raise RuntimeError('glxinfo did not confirm the actual Mesa llvmpipe renderer')
    report = {
        'repository': os.environ.get('GITHUB_REPOSITORY'),
        'source_head': head,
        'run_id': os.environ.get('GITHUB_RUN_ID'),
        'run_attempt': os.environ.get('GITHUB_RUN_ATTEMPT'),
        'captured_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'platform': 'Linux X11 native window under Xvfb',
        'renderer': renderer_lines[0],
        'method': 'Existing fontstrike-desktop --capture; native egui Screenshot event; unchanged glow renderer; no UI stand-in',
        'fixture': 'Synthetic test font generated by src/demo.rs; no user font or device opened',
        'status': 'running', 'images': [],
    }
    provenance = output / 'provenance.json'

    def save_report() -> None:
        provenance.write_text(json.dumps(report, indent=2) + '\n')

    save_report()
    demo = output / 'FontStrikeTestSans.ufo'
    cases = [
        ('splash', '1280x800', []),
        ('editor-A', '1280x800', ['--demo', str(demo), '--select', 'A']),
        ('editor-o-point-selected', '1280x800', ['--project', str(demo), '--select', 'o', '--point', '0:0']),
        ('about', '1280x800', ['--about']),
        ('editor-narrow-1000x680', '1000x680', ['--project', str(demo), '--select', 'V']),
    ]
    try:
        for name, size, arguments in cases:
            png = output / f'{name}.png'
            if png.exists():
                raise RuntimeError(f'Refusing a pre-existing capture file: {png}')
            argv = [str(app), '--size', size, '--capture', str(png), *arguments]
            stdout = output / f'{name}-stdout.txt'
            stderr = output / f'{name}-stderr.txt'
            with stdout.open('wb') as out, stderr.open('wb') as err:
                process = subprocess.run(argv, stdout=out, stderr=err, timeout=45, check=False)
            out_text, err_text = stdout.read_text(), stderr.read_text()
            if process.returncode != 0:
                raise RuntimeError(f'Native {name} process exited {process.returncode}: {err_text[-4000:]}')
            if any(error in err_text for error in ('Test font:', 'Open font:', 'Capture failed:')):
                raise RuntimeError(f'Native app reported an error for {name}: {err_text[-4000:]}')
            if f'Captured {png}' not in out_text:
                raise RuntimeError(f'Native app did not acknowledge its own framebuffer capture: {name}')
            report['images'].append(validate_native_png(png))
            save_report()
        if not (demo / 'metainfo.plist').is_file():
            raise RuntimeError('Synthetic test font was not created')
        if len({image['sha256'] for image in report['images']}) != len(cases):
            raise RuntimeError('Expected distinct native views, but two PNGs are identical')
        report['status'] = 'passed'
        save_report()
    except Exception as error:
        report['status'] = 'failed'
        report['error'] = str(error)
        save_report()
        raise


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit('usage: ci_native_capture.py NATIVE_APP OUTPUT_DIRECTORY')
    capture(Path(sys.argv[1]).resolve(strict=True), Path(sys.argv[2]).resolve())
